// Builds SAT Wizz: Clause Derby as one self-contained file: clause-derby/index.html
//
//   node scripts/build-clause-derby.js
//
// Inlines the shared race engine and sounds from the SatWizz app (js/derby.js,
// js/sfx.js) plus the Clause Derby sources in clause-derby/src/. Re-run after
// changing any of them. Google Fonts are optional; the page works offline.
"use strict";

const fs = require("fs");
const path = require("path");

const repo = path.resolve(__dirname, "..");
const read = (f) => fs.readFileSync(path.join(repo, f), "utf8");
const safeScript = (code) => code.replace(/<\/script/gi, "<\\/script");
const safeStyle = (code) => code.replace(/<\/style/gi, "<\\/style");

const SCRIPTS = [
  "js/derby.js", // race engine: CPU rivals, live clock, tactics
  "js/sfx.js", // Web Audio sounds + vibration
  "clause-derby/src/bank.js",
  ...[1, 2, 3, 4, 5, 6, 7].map((n) => `clause-derby/src/ch${n}.js`),
  "clause-derby/src/app.js",
];

const js = SCRIPTS.map((f) => `\n/* ===== ${f} ===== */\n${read(f)}`).join("\n");
const css = read("clause-derby/src/styles.css");

const html = `<!doctype html>
<!-- SAT Wizz: Clause Derby. Generated by scripts/build-clause-derby.js; edit clause-derby/src and rebuild. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>SAT Wizz: Clause Derby</title>
<meta name="description" content="SAT Wizz: Clause Derby. Race seven CPU rivals through a 7-chapter Digital SAT grammar curriculum: clause connectors, subject-verb agreement, verbs vs. non-verbs, tenses, transitions, punctuation and appositives.">
<meta name="theme-color" content="#0b1020">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'%3E%3Ctext y='.9em' font-size='90'%3E%F0%9F%90%8E%3C/text%3E%3C/svg%3E">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&family=Plus+Jakarta+Sans:wght@600;700;800&display=swap">
<style>
${safeStyle(css)}
</style>
</head>
<body>
<div id="app"></div>
<noscript><p style="padding:16px">SAT Wizz: Clause Derby needs JavaScript to run.</p></noscript>
<script>
window.SatWizz = window.SatWizz || {};
${safeScript(js)}
</script>
</body>
</html>
`;

const out = path.join(repo, "clause-derby", "index.html");
fs.writeFileSync(out, html);
console.log(`wrote ${path.relative(repo, out)} (${(html.length / 1024).toFixed(0)} KB)`);
